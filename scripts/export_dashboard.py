"""Export real seeded trajectories and the phase registry for the observatory.

Run from the repository root: python -m scripts.export_dashboard --seed 42
"""

import argparse
from datetime import datetime, timezone
import json
from pathlib import Path

from biocontrolos.process.fermentation.simulator import FermentationSimulator

ROOT = Path(__file__).resolve().parents[1]
CHANNELS = [
    ("biomass", "Biomass", "g/L", "state"),
    ("penicillin", "Penicillin", "g/L", "state"),
    ("substrate", "Substrate", "g/L", "observation"),
    ("dissolved_oxygen", "Dissolved oxygen", "mg/L", "observation"),
    ("pH", "pH", "pH", "observation"),
    ("temperature", "Temperature", "K", "observation"),
    ("volume", "Volume", "L", "observation"),
]


def export(seed: int, destination: Path) -> Path:
    batch = FermentationSimulator(seed=seed).run_batch()
    run_id = f"baseline-seed-{seed}"
    payload = {
        "schemaVersion": "1.0", "id": run_id,
        "label": "Baseline fermentation", "seed": seed, "simulator": "IndPenSim",
        "generatedAt": datetime.now(timezone.utc).isoformat(),
        "provenance": "Generated by TELESTO FermentationSimulator. Default batch flags: 0/0/0/0. Local upstream revision and license unverified. Channel units follow the local IndPenSim batch definitions.",
        "channels": [dict(zip(("key", "label", "unit", "role"), c)) for c in CHANNELS],
        "samples": [
            {"time": round(float(batch.time[i] - batch.time[0]), 8),
             **{key: float(getattr(batch, key)[i]) for key, *_ in CHANNELS}}
            for i in range(batch.samples)
        ],
    }
    destination.mkdir(parents=True, exist_ok=True)
    (destination / "runs").mkdir(exist_ok=True)
    target = destination / "runs" / f"{run_id}.json"
    temporary = target.with_suffix(".tmp")
    temporary.write_text(json.dumps(payload, separators=(",", ":"), allow_nan=False), encoding="utf-8")
    temporary.replace(target)
    registry = json.loads((ROOT / "configs/dashboard.json").read_text(encoding="utf-8"))
    # Retain other exported seeds and future-phase runs already in this destination.
    if (destination / "workspace.json").exists():
        old = json.loads((destination / "workspace.json").read_text(encoding="utf-8"))
        known = {r["id"] for r in registry["runs"]}
        registry["runs"].extend(r for r in old["runs"] if r["id"] not in known)
    if not any(r["id"] == run_id for r in registry["runs"]):
        registry["runs"].append({"id": run_id, "label": "Baseline fermentation", "phaseId": "digital-twin", "seed": seed, "kind": "Seeded simulation"})
    registry["runs"] = [r for r in registry["runs"] if (destination / "runs" / f"{r['id']}.json").is_file()]
    registry_path = destination / "workspace.json"
    temporary = registry_path.with_suffix(".tmp")
    temporary.write_text(json.dumps(registry, indent=2), encoding="utf-8")
    temporary.replace(registry_path)
    print(f"Exported {batch.samples} samples over {batch.duration_hours:.1f} h to {target}")
    return target


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--seed", type=int, default=42)
    parser.add_argument("--output", type=Path, default=ROOT / "apps/dashboard/public/demo")
    args = parser.parse_args()
    if not 0 <= args.seed < 2**32:
        parser.error("seed must be between 0 and 4294967295")
    export(args.seed, args.output)
